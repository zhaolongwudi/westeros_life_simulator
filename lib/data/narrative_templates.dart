/// 叙事引导模板（Batch 10-9）。
///
/// 为 AI 叙事提供按「身份 / 地点区域 / 季节」差异化的叙事线索，
/// 让同样的情境在不同身份、不同区域、不同季节下产生不同的叙事走向。
/// 纯数据层：零状态、零迁移，只影响 AI 提示词构建。
library;

import '../models/player.dart';

/// 按身份返回差异化叙事引导（3~4 条线索）。
///
/// 每个身份一组叙事视角：身份决定玩家能看到的世界、关心的事、
/// 可利用的资源、以及叙事中自然浮现的冲突类型。
String identityNarrativeGuide(PlayerIdentity identity) {
  return switch (identity) {
    PlayerIdentity.noble => '''
- 你出身贵族：家族荣誉、继承权、联姻与领地是悬在头顶的剑
- 叙事偏向权力与阴谋：封臣的忠诚、君主的猜忌、家族的隐秘
- 你可以调动家族资源，但每个决定都会在家族内部引发回响
- 别让 AI 把你写成平民——你的餐桌上有银器，你的敌人穿着天鹅绒''',
    PlayerIdentity.commoner => '''
- 你是一介平民：税赋、生计、口粮是每天睁开眼就要面对的事
- 叙事偏向生存与日常：领主征税、收成好坏、集市价格、兵役征召
- 你无权无势，但自由——你可以选择在任何地方成为任何人
- 别让 AI 把你写成贵族——你更熟悉泥土而不是绸缎''',
    PlayerIdentity.soldier => '''
- 你是一名士兵：军饷、战功、荣誉与活下来是四条并行的路
- 叙事偏向战争与服从：长官的命令、战场的号角、城头的攻防
- 你可以用刀说话，但刀锋之后是纪律、忠诚与牺牲
- 别让 AI 把你写成将军——你还在为每一枚铜板军饷拼命''',
    PlayerIdentity.merchant => '''
- 你是一名商人：金币即权力，商路即血脉
- 叙事偏向经济与契约：货物、关税、运费、市集行情、借贷与抵押
- 你善于用钱开路，但乱世里金币买不来忠诚，也挡不住刀剑
- 别让 AI 把你写成贵族——你的武器是算盘而不是长剑''',
    PlayerIdentity.priest => '''
- 你是一名神职人员：信仰是最锋利的武器
- 叙事偏向宗教与人心：七神的教诲、旧神的低语、信徒的忏悔与狂热
- 你站在神与人之间，可以抚慰，也可以审判
- 别让 AI 把你写成骑士——你更习惯祈祷室而不是比武场''',
    PlayerIdentity.scholar => '''
- 你是一名学者：知识即力量，真相有时比剑更致命
- 叙事偏向知识与秘密：古卷、书信、学城的争论、被遗忘的历史
- 你追求真相，但真相往往有代价——学城不是避难所
- 别让 AI 把你写成战士——你更常握笔而不是握剑''',
    PlayerIdentity.adventurer => '''
- 你是一名冒险者：世界的每个角落都在向你招手
- 叙事偏向远方与未知：陌生土地、古老废墟、危险与财宝并存
- 你没有根基，但也因此自由——今天在君临，明天可能在厄索斯
- 别让 AI 把你困在一个地方——你的天性就是向前''',
    PlayerIdentity.assassin => '''
- 你是一名刺客：阴影中的交易，见血封喉
- 叙事偏向暗影与代价：契约、毒药、潜行、不可见的威胁
- 你的名字不出现在任何人的谈话里，但你的刀锋被人敬畏
- 别让 AI 把你写成侠客——你不是为正义杀人，是为钱''',
    PlayerIdentity.maester => '''
- 你是一名学士：渡鸦、锁链与誓言
- 叙事偏向知识与中立：学城赋予你智慧，誓言束缚你不偏不倚
- 你为领主服务，但你的忠诚首先属于学城与知识
- 别让 AI 把你写成普通学者——你的脖子上戴着学士的锁链''',
    PlayerIdentity.wildling => '''
- 你是一名野人：长城之外，自由民的血性
- 叙事偏向荒野与生存：长城、森林、部落、凛冬的威胁
- 你不跪任何王，但你也得不到任何王国的保护
- 别让 AI 把你写成南方贵族——你穿兽皮而不是丝绸''',
  };
}

/// 按地点区域返回差异化叙事引导（1~2 条）。
///
/// 区域决定地理与政治底色：北境的严酷、王领的权力、厄索斯的异域……
String regionNarrativeGuide(String region) {
  return switch (region) {
    '北境' => '北境苦寒，史塔克家族的信条「凛冬将至」不是玩笑——这里的冬天能冻死人的野心。',
    '河间地' => '河间地位于四战之地，赫伦堡的废墟提醒着所有人：这里谁强谁说了算。',
    '谷地' => '谷地有鹰巢城的险峻与月门的孤高，艾林家族守着「高如荣誉」的誓言。',
    '西境' => '西境有凯岩城的金矿与兰尼斯特的傲慢，金子在这里比血更响亮。',
    '河湾地' => '河湾地丰饶富庶，高庭的玫瑰与提利尔的算计并存，宴席与政治从不分家。',
    '王领' => '王领是七国的中心，君临的红堡里权力更迭比季节更快，跳蚤窝与铁王座只有一墙之隔。',
    '风暴地' => '风暴地常年受风暴洗礼，拜拉席恩家族世代与怒海搏斗，坚毅写在每个风暴人的脸上。',
    '多恩' => '多恩酷热，马泰尔家族有「不屈不挠」的族语，这里的人对仇恨与爱情同样炽烈。',
    '铁群岛' => '铁群岛的船民信奉淹神，他们的信条是「我们不上税」——掠夺是他们的生计。',
    '厄索斯' => '厄索斯是异域之地：自由贸易城邦的金库、奴隶湾的锁链、多斯拉克人的马背——这里没有维斯特洛的规矩。',
    '超自然' => '这里游离于常理之外：古老的力量在低语，现实的边界正在松动——小心脚下。',
    '未知世界' => '这里是地图的空白处，没有人知道前方有什么——这正是它危险又迷人的原因。',
    _ => '这片土地有自己的脾气，叙事应贴合其地理与政治底色。',
  };
}

/// 按季节返回差异化叙事引导（1~2 条）。
String seasonNarrativeGuide(String season) {
  return switch (season) {
    'spring' => '春天冰雪消融，道路渐通，集市恢复热闹——但也正是权力重新洗牌的时候。',
    'summer' => '盛夏漫长，谷物生长，领主们有余力发起战争或结盟——夏天是行动的季节。',
    'autumn' => '秋日丰收在望，但聪明的领主已经开始储备——长夏之后必有凛冬。',
    'winter' => '严冬已至，大雪封路，物价飞涨，饥饿与疾病开始收割——生存压倒一切体面。',
    'longwinter' => '凛冬降临，这是能持续数年的死亡之冬——长城之外的威胁与南方的饥荒同时逼近。',
    _ => '季节更替影响着旅途、收成与人心，叙事应体现时令的力量。',
  };
}

/// 按季节返回「季节世界动向」（Batch 10-50）。
///
/// 与 [seasonNarrativeGuide] 的玩家视角引导不同，本函数提供**整个维斯特洛**的
/// 时令动向：当前季节下各势力/各区域的宏观变化，供 AI 叙事围绕「季节驱动世界」
/// 展开，让玩家感受到世界正在随着时令呼吸。
String seasonWorldTrend(String season) {
  return switch (season) {
    'spring' =>
      '春潮涌动：积雪化尽，道路重新贯通，商队与信使往来频繁；君临的权力天平因解冻的航道而摇摆，'
          '北境刚熬过严冬的领地开始清点损失，各大家族趁着道路畅通重开联姻与结盟的谈判。',
    'summer' =>
      '盛夏正酣：粮仓渐满，领主们有余力兴兵、比武与联姻；君临的宴会一场接一场，'
          '河湾地的收成喂饱了半个王国，西境的金库因贸易而膨胀，多恩的太阳晒得野心发酵。',
    'autumn' =>
      '秋色渐浓：丰收让谷仓堆满，但精明的领主已经开始囤积过冬的物资，粮价悄然爬升；'
          '长城以北的动静比往年更早传来，南方的贵族们则忙着在入冬前办完婚事与比武大会。',
    'winter' =>
      '严冬笼罩：大雪封住隘口，粮价飞涨，饥饿与疫病开始在城镇蔓延；君临的宫廷为粮仓配额争吵不休，'
          '北境人沉默地挨饿，长城守军报告野人部落向南方迁徙——一切都慢了下来，只有死亡在加速。',
    'longwinter' =>
      '凛冬无期：这场冬天已持续多年，河流冰封，兽群绝迹，南方也未能幸免——饥荒、逃亡与瘟疫轮番收割；'
          '长城之外的异鬼传说不再是篝火边的故事，学城的学士们承认：大陆正在被这场永冬慢慢吞噬。',
    _ => '季节轮转如常：各大家族随农时与商路调整着棋局，世界在时令的节拍里缓慢呼吸。',
  };
}
