    'autumn' => '秋日丰收在望，但聪明的领主已经开始储备——长夏之后必有凛冬。',
    'winter' => '严冬已至，大雪封路，物价飞涨，饥饿与疾病开始收割——生存压倒一切体面。',
    'longwinter' => '凛冬降临，这是能持续数年的死亡之冬——长城之外的威胁与南方的饥荒同时逼近。',
    _ => '季节更替影响着旅途、收成与人心，叙事应体现时令的力量。',
  };
