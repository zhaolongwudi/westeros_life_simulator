  for (final l in allLocations) {
    if (l.id == id) return l;
  }
  return null;
}

/// 按区域筛选地点。
List<Location> locationsByRegion(String region) {
  return allLocations.where((l) => l.region == region).toList();
}

/// 按危险度筛选地点。
List<Location> locationsByDangerLevel(int minLevel, [int maxLevel = 6]) {
  return allLocations
      .where((l) => l.dangerLevel >= minLevel && l.dangerLevel <= maxLevel)
      .toList();
}