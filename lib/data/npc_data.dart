    if (n.id == id) return n;
  }
  return null;
}

/// 按家族筛选 NPC。
List<Npc> npcsByFamily(String familyId) {
  return allNpcs.where((n) => n.familyId == familyId).toList();
}

/// 按地点筛选 NPC。
List<Npc> npcsByLocation(String locationId) {
  return allNpcs.where((n) => n.locationId == locationId).toList();
}