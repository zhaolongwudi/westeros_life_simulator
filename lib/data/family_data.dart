/// 按 ID 查找家族。
Family? familyById(String id) {
  for (final f in allFamilies) {
    if (f.id == id) return f;
  }
  return null;
}

/// 按地区筛选家族。
List<Family> familiesByRegion(String region) {
  return allFamilies.where((f) => f.seat.contains(region)).toList();
}